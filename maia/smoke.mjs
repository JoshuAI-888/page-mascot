import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || '@playwright/test')
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const url = process.env.DEMO_URL || 'http://127.0.0.1:4318/'
const out = process.env.EVIDENCE_DIR || 'maia-evidence'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' })
const results = [], errors = []
const check = (name) => results.push({ name, passed: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1150 } })
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(url)
  const stage = page.getByRole('button', { name: 'Boop the Māia on the stage', exact: true })
  await page.getByRole('button', { name: 'Everyday', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.action-grid button').disabled)
  await page.getByLabel('Automatic idle moments').uncheck()
  await page.getByLabel('Follow the pointer').uncheck()
  for (const action of ['Smile', 'Blink', 'Scratch', 'Look around', 'Bored', 'Excited', 'Heart', 'Sparkle', 'Surprised', 'Wink', 'Bashful', 'Sleepy', 'Dizzy', 'Delighted', 'Curious', 'Thinking', 'Listening', 'Understanding', 'Unsure', 'Encouraging', 'Proud', 'Concerned', 'Welcoming', 'Celebrating', 'Reading', 'Waiting patiently', 'Noticing something', 'Pointing']) {
    if (action === 'Curious') await page.getByRole('button', { name: 'Expressions', exact: true }).click()
    if (action === 'Reading') await page.getByRole('button', { name: 'On the page', exact: true }).click()
    await page.getByRole('button', { name: action, exact: true }).click({ timeout: 5000 })
    await page.waitForFunction(value => document.querySelector('[data-testid=state]').textContent === value, action)
    assert.equal(await page.getByTestId('state').innerText(), action)
    await page.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Idle', { timeout: 5000 })
    check(`${action} starts and returns to idle`)
  }
  await page.getByRole('button', { name: 'Everyday', exact: true }).click()
  await page.getByRole('button', { name: /Scratch/ }).click()
  await page.waitForTimeout(280)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const frozen = await stage.getAttribute('data-frame')
  await page.waitForTimeout(500)
  assert.equal(await stage.getAttribute('data-frame'), frozen)
  await page.screenshot({ path: `${out}/desktop-scratch.png`, fullPage: true })
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Idle')
  check('Pause freezes the current pose; resume completes the sequence')
  for (let i = 0; i < 4; i++) await stage.click()
  await page.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Dizzy')
  await page.waitForTimeout(1200)
  check('Four rapid boops trigger dizzy')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByLabel('Follow the pointer').check()
  const bounds = await stage.boundingBox()
  await page.mouse.move(bounds.x + bounds.width / 2 + 240, bounds.y + bounds.height / 2)
  await page.waitForTimeout(100)
  assert.equal(await stage.getAttribute('data-frame'), '5')
  await page.mouse.move(bounds.x + bounds.width / 2 - 240, bounds.y + bounds.height / 2)
  await page.waitForTimeout(100)
  assert.equal(await stage.getAttribute('data-frame'), '3')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  assert.equal(await stage.getAttribute('data-frame'), '4')
  check('Pointer sectors and centre dead zone')
  await stage.focus(); await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Heart')
  await page.waitForTimeout(650)
  await page.keyboard.press('Space')
  await page.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Sparkle')
  check('Keyboard Enter and Space activate the mascot')
  await page.getByRole('button', { name: 'Hide corner companion' }).click()
  assert.equal(await page.locator('.dock').count(), 0)
  await page.getByLabel('Corner companion').check()
  assert.equal(await page.locator('.dock').count(), 1)
  check('Corner companion hides and restores')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByLabel('Follow the pointer').uncheck()
  await page.getByRole('button', { name: 'Expressions', exact: true }).click()
  await page.screenshot({ path: `${out}/desktop.png`, fullPage: true })
  await page.getByRole('button', { name: 'Change stage background' }).click()
  await page.screenshot({ path: `${out}/dark-stage.png`, fullPage: true })
  await page.getByRole('button', { name: 'Change stage background' }).click()
  await page.getByLabel('Reduced motion', { exact: false }).check()
  await page.getByRole('button', { name: 'Everyday', exact: true }).click()
  await page.getByRole('button', { name: /Excited/ }).click()
  const still = await stage.getAttribute('data-frame')
  await page.waitForTimeout(600)
  assert.equal(await stage.getAttribute('data-frame'), still)
  check('Reduced motion holds a still pose')
  await page.getByLabel('Reduced motion', { exact: false }).uncheck()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByLabel('Automatic idle moments').check()
  await page.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Blink', { timeout: 9000 })
  check('Automatic idle triggers a blink')
  await page.getByLabel('Automatic idle moments').uncheck()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByText('Inspect the nine gaze directions', { exact: true }).click()
  const labels = ['Up left','Up','Up right','Left','Centre','Right','Down left','Down','Down right']
  for (let i=0; i<labels.length; i++) {
    await page.getByRole('button', { name: labels[i], exact: true }).click()
    assert.equal(await stage.getAttribute('data-frame'), `${i}`)
  }
  check('All nine atlas direction controls')
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
  mobile.on('pageerror', e => errors.push(e.message))
  await mobile.goto(url)
  await mobile.waitForFunction(() => !document.querySelector('.action-grid button').disabled)
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await mobile.getByRole('button', { name: 'Everyday', exact: true }).click()
  await mobile.getByRole('button', { name: /Excited/ }).click()
  await mobile.waitForFunction(() => document.querySelector('[data-testid=state]').textContent === 'Excited')
  assert.equal(await mobile.getByTestId('state').innerText(), 'Excited')
  await mobile.getByRole('button', { name: 'Pause', exact: true }).click()
  await mobile.screenshot({ path: `${out}/mobile.png`, fullPage: true })
  check('390px touch layout: no overflow; action and pause work')
  const reduce = await browser.newPage({ reducedMotion: 'reduce' })
  await reduce.goto(url)
  const reducedToggle = reduce.getByLabel('Reduced motion', { exact: false })
  assert.equal(await reducedToggle.isChecked(), true)
  assert.equal(await reducedToggle.isDisabled(), true)
  check('Device reduced-motion preference is respected')
  assert.deepEqual(errors, [])
  check('No browser runtime errors')
} finally {
  await browser.close()
  await writeFile(`${out}/results.json`, JSON.stringify({ url, checks: results, errors, completed: new Date().toISOString() }, null, 2))
}
console.log(JSON.stringify({ passed: results.length, errors }))
